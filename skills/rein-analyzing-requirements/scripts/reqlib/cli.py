"""Command-line parsing for scripts/req.py.

Every command is non-interactive: all input comes from arguments, the result
is one JSON object on stdout (see output.py), and each command's --help ends
with an example.
"""

from __future__ import annotations

import argparse
import platform
from typing import Callable, Sequence

from . import SKILL_NAME, __version__
from .commands import HANDLERS
from .output import Stop, finish, issue, use_utf8_streams
from .settings import LANGS

OUTPUTS = ("brief", "plan", "sql", "release", "frontend")
SEND_TARGETS = ("frontend", "self", "all")
CONFIG_KEYS = ("workspace", "lang")
CONFIG_SCOPES = ("project", "user")

RUN = "python3 scripts/req.py"

MAIN_DESCRIPTION = """\
Turn a requirement document into a checked analysis and the files a team
builds from: requirement brief, backend plan, table SQL, release checklist,
frontend API guide.

Edit only the analysis files (analysis.json, frontend.json). Every page and
SQL file is generated by `render`; never write them by hand.
"""

MAIN_EPILOG = """\
where to run:
  From the project directory (not the skill folder): project settings in
  .req-profile.json are found from there.

output:
  stdout  one JSON object: {"ok", "command", ..., "issues": [...]}
          each issue: {"code", "level", "where", "msg", "hint"}
          level is "error" (must fix), "warn" (worth a look) or
          "confirm" (stop and ask the user)
  stderr  progress notes and reminders

exit codes:
  0  done; no error or confirm issues
  1  done, but there are error or confirm issues (see "issues")
  2  bad arguments, missing files or settings, or Python older than 3.9

which python command:
  python3 scripts/req.py ...      (macOS, Linux)
  python scripts/req.py ...       (Windows, when python3 is missing)
  py -3 scripts/req.py ...        (Windows launcher)
  uv run scripts/req.py ...       (anywhere uv is installed)
  Run --version first to find one that works.

example:
  %(run)s new --doc prd.md --name activity-signup
  %(run)s check --req activity-signup
  %(run)s render --req activity-signup
""" % {"run": RUN}


class _Formatter(argparse.RawDescriptionHelpFormatter):
    """Keep the line breaks in descriptions and examples."""


def _csv_of(allowed: Sequence[str]) -> Callable[[str], list[str]]:
    """Argument type for comma-separated values, each from `allowed`."""

    def parse(text: str) -> list[str]:
        items = [part.strip() for part in text.split(",") if part.strip()]
        bad = [item for item in items if item not in allowed]
        if not items or bad:
            raise argparse.ArgumentTypeError(
                "expected a comma-separated list of: %s" % ", ".join(allowed)
            )
        return items

    return parse


def _positive_int(text: str) -> int:
    try:
        value = int(text)
    except ValueError:
        value = 0
    if value < 1:
        raise argparse.ArgumentTypeError("expected a whole number >= 1")
    return value


def _not_implemented(command: str) -> Callable[[argparse.Namespace], int]:
    def handler(args: argparse.Namespace) -> int:
        return finish(
            command,
            [
                issue(
                    "cli.not-implemented",
                    "error",
                    "'%s' is not implemented yet." % command,
                    hint="This build is a skeleton; only --help and --version work.",
                )
            ],
        )

    return handler


def _add_command(
    subparsers: argparse._SubParsersAction,
    name: str,
    summary: str,
    description: str,
    examples: Sequence[str],
    full_name: str = "",
) -> argparse.ArgumentParser:
    epilog = "example:\n" + "\n".join("  %s %s" % (RUN, line) for line in examples)
    parser = subparsers.add_parser(
        name,
        help=summary,
        description=description,
        epilog=epilog,
        formatter_class=_Formatter,
        allow_abbrev=False,
    )
    command = full_name or name
    parser.set_defaults(handler=HANDLERS.get(command) or _not_implemented(command), command_name=command)
    return parser


def _add_req_options(parser: argparse.ArgumentParser) -> None:
    """Options shared by every command that works on one existing requirement."""
    parser.add_argument(
        "--req",
        required=True,
        metavar="REQ",
        help="which requirement: its short name (activity-signup) or "
        "folder name (REQ-20261118-activity-signup)",
    )
    _add_dir_option(parser)


def _add_dir_option(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--dir",
        metavar="DIR",
        help="requirements folder for this run only; overrides the project "
        "and user settings",
    )


def _add_all_option(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--all",
        action="store_true",
        help="list every issue (by default: a summary and the first 50)",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="req.py",
        description=MAIN_DESCRIPTION,
        epilog=MAIN_EPILOG,
        formatter_class=_Formatter,
        allow_abbrev=False,
    )
    parser.add_argument(
        "--version",
        action="version",
        version="%s %s (Python %s)" % (SKILL_NAME, __version__, platform.python_version()),
    )
    sub = parser.add_subparsers(dest="command", metavar="<command>", title="commands")
    sub.required = True

    p = _add_command(
        sub,
        "new",
        "create a requirement folder from a document",
        "Create a requirement folder and store the document as source version 1.\n"
        "Read a URL into a Markdown file first and pass that file.\n"
        "If no requirements folder has been chosen yet, nothing is created: the\n"
        "result says so and suggests places to ask the user about.\n"
        "Running it again for an existing requirement reports where it is and\n"
        "changes nothing.",
        [
            "new --doc prd.md --name activity-signup",
            "new --doc prd.md --name activity-signup --lang en",
        ],
    )
    p.add_argument("--doc", required=True, metavar="FILE", help="the requirement document (Markdown or text)")
    p.add_argument(
        "--name",
        required=True,
        metavar="SHORT",
        help="short name: lowercase letters, digits and hyphens (activity-signup)",
    )
    p.add_argument(
        "--lang",
        choices=LANGS,
        help="language of the generated files; fixed for this requirement once "
        "created (default: project setting, then user setting, then zh-CN)",
    )
    _add_dir_option(p)

    p = _add_command(
        sub,
        "example",
        "print a format sample",
        "Print a complete format sample based on a made-up 'activity signup'\n"
        "requirement. Copy the shape, not the content.",
        ["example", "example frontend"],
    )
    p.add_argument(
        "kind",
        nargs="?",
        default="analysis",
        choices=("analysis", "frontend"),
        help="which file to show (default: analysis)",
    )

    p = _add_command(
        sub,
        "check",
        "check the analysis and list issues",
        "Check the analysis for format, length, coverage of the source document,\n"
        "consistency and language, and list the issues found.",
        ["check --req activity-signup", "check --req activity-signup --frontend"],
    )
    _add_req_options(p)
    p.add_argument("--frontend", action="store_true", help="check frontend.json instead of analysis.json")
    _add_all_option(p)

    p = _add_command(
        sub,
        "render",
        "save a version and generate pages and SQL",
        "Check the analysis (nothing is generated while check reports errors or\n"
        "confirm items), save it as a new version if it changed, then generate the\n"
        "pages into out/. Pages that are not needed are not generated. A page\n"
        "someone edited by hand is kept and the new one is saved beside it.\n"
        "Change marks compare with the copy last sent; before anything is sent\n"
        "there are none, unless --since names a version to compare with.",
        [
            "render --req activity-signup",
            "render --req activity-signup --since 3",
            "render --req activity-signup --only brief",
        ],
    )
    _add_req_options(p)
    p.add_argument("--frontend", action="store_true", help="also generate the frontend API guide")
    p.add_argument(
        "--only",
        type=_csv_of(OUTPUTS),
        metavar="LIST",
        help="generate only these, comma-separated: %s" % ",".join(OUTPUTS),
    )
    p.add_argument("--since", type=_positive_int, metavar="VERSION",
                   help="mark changes since this analysis version")
    p.add_argument("--force", action="store_true", help="replace pages even if they were edited by hand")

    p = _add_command(
        sub,
        "status",
        "report what is out of date",
        "Report where the requirement stands and what is out of date: the analysis\n"
        "changed but was not rendered, the document is newer than the analysis,\n"
        "answered questions not yet applied, pages missing, outdated or edited by\n"
        "hand, environments whose SQL is behind, and whether check passes. Each\n"
        "finding is a warn issue whose hint is the next step. Changes nothing.",
        ["status --req activity-signup"],
    )
    _add_req_options(p)

    p = _add_command(
        sub,
        "refresh",
        "store a new version of the document",
        "Store a new version of the requirement document and list what changed,\n"
        "section by section.",
        ["refresh --req activity-signup --doc prd-v2.md"],
    )
    _add_req_options(p)
    p.add_argument("--doc", required=True, metavar="FILE", help="the new version of the document")

    p = _add_command(
        sub,
        "send",
        "record a send and print a team notice",
        "Run the strict pre-send check, record that the files were sent, and\n"
        "print a notice ready to paste into the team chat. Pages compare against\n"
        "the version this reader last received.",
        ["send --req activity-signup --to frontend"],
    )
    _add_req_options(p)
    p.add_argument("--to", required=True, choices=SEND_TARGETS, help="who receives the files")
    _add_all_option(p)

    p = _add_command(
        sub,
        "applied",
        "record which SQL version ran in an environment",
        "Record that the SQL up to analysis version N has been run in an\n"
        "environment. Later SQL patches for that environment start from there.",
        ["applied --req activity-signup --env test --v 3"],
    )
    _add_req_options(p)
    p.add_argument("--env", required=True, metavar="ENV", help="environment name from the project settings (test)")
    p.add_argument("--v", required=True, type=_positive_int, metavar="VERSION", help="analysis version that was run")

    p = _add_command(
        sub,
        "contract",
        "store an API description for the frontend guide",
        "Store an API description (OpenAPI JSON). render uses it to fill paths,\n"
        "parameters and response fields in the frontend API guide.",
        [
            "contract --req activity-signup --openapi openapi.json",
            "contract --req activity-signup --openapi http://localhost:8080/v3/api-docs",
        ],
    )
    _add_req_options(p)
    p.add_argument("--openapi", required=True, metavar="FILE_OR_URL", help="OpenAPI JSON file or URL")

    p = _add_command(
        sub,
        "export",
        "export the backend plan (XMind)",
        "Export the backend plan as an XMind file, with owners on the nodes.",
        ["export xmind --req activity-signup"],
    )
    p.add_argument("format", choices=("xmind",), help="export format")
    _add_req_options(p)

    p = _add_command(
        sub,
        "config",
        "remember settings (requirements folder, language)",
        "Remember a setting so it is not asked again.\n"
        "  project settings: .req-profile.json in the project root\n"
        "  user settings:    the user config, used by every project",
        ["config set workspace docs/requirements"],
    )
    config_sub = p.add_subparsers(dest="action", metavar="<action>", title="actions")
    config_sub.required = True
    p = _add_command(
        config_sub,
        "set",
        "set one setting",
        "Set one setting.\n"
        "  workspace  where requirement folders go. The folder decides where it is\n"
        "             saved: inside the project -> project settings (stored relative);\n"
        "             outside -> user settings (all projects). No --scope needed.\n"
        "  lang       language of generated files: %s. Needs --scope." % ", ".join(LANGS),
        [
            "config set workspace docs/requirements",
            "config set workspace ~/Documents/requirements",
            "config set lang en --scope user",
        ],
        full_name="config set",
    )
    p.add_argument("key", choices=CONFIG_KEYS, help="setting name")
    p.add_argument("value", help="new value")
    p.add_argument(
        "--scope",
        choices=CONFIG_SCOPES,
        help="project or user; required for lang; for workspace it must match the folder's location",
    )

    return parser


def main(argv: Sequence[str] | None = None) -> int:
    use_utf8_streams()
    args = build_parser().parse_args(argv)
    try:
        return args.handler(args)
    except Stop as stop:
        return finish(args.command_name, [stop.issue], exit_code=stop.exit_code, **stop.fields)
